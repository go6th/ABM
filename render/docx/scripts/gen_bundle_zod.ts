// Turns the AccountBundle JSON Schema (src/parity/schema/account_bundle.schema.json at the
// repository root) into a zod schema, src/bundle.gen.ts. The subset it understands is the subset
// the schema uses: object, array, string, integer, number, boolean, null and lists of those,
// enum, pattern, min and max lengths, minimum and maximum, minItems and maxItems, required,
// additionalProperties (false, or a schema for a map), propertyNames with a pattern, and $ref
// into $defs. `format` is an annotation in JSON Schema 2020-12 and stays one here: nothing is
// asserted for it. Unknown keys are rejected everywhere additionalProperties is false, like the
// JSON Schema does. Run with `npm run gen`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

type Schema = Record<string, unknown>;

const here = dirname(fileURLToPath(import.meta.url));
const schemaPath = resolve(here, "../../../src/parity/schema/account_bundle.schema.json");
const outPath = resolve(here, "../src/bundle.gen.ts");

const root = JSON.parse(readFileSync(schemaPath, "utf8")) as Schema;
const defs = (root.$defs ?? {}) as Record<string, Schema>;
const defNames: string[] = [];

function str(s: Schema): string {
  let z = "z.string()";
  if (typeof s.minLength === "number") z += `.min(${s.minLength})`;
  if (typeof s.maxLength === "number") z += `.max(${s.maxLength})`;
  if (typeof s.pattern === "string") z += `.regex(new RegExp(${JSON.stringify(s.pattern)}))`;
  return z;
}

function num(s: Schema, integer: boolean): string {
  let z = integer ? "z.number().int()" : "z.number()";
  if (typeof s.minimum === "number") z += `.min(${s.minimum})`;
  if (typeof s.maximum === "number") z += `.max(${s.maximum})`;
  return z;
}

function obj(s: Schema): string {
  const props = (s.properties ?? {}) as Record<string, Schema>;
  const required = new Set((s.required ?? []) as string[]);
  const extra = s.additionalProperties;
  const names = Object.keys(props);
  if (names.length === 0 && extra !== false) {
    // a map: every key allowed (optionally matching propertyNames), values of one shape
    const keyPattern = ((s.propertyNames as Schema | undefined)?.pattern as string | undefined);
    const key = keyPattern ? `z.string().regex(new RegExp(${JSON.stringify(keyPattern)}))` : "z.string()";
    const value = extra && typeof extra === "object" ? gen(extra as Schema) : "z.unknown()";
    return `z.record(${key}, ${value})`;
  }
  const lines = names.map((n) => {
    const v = gen(props[n] as Schema);
    return `  ${JSON.stringify(n)}: ${required.has(n) ? v : `${v}.optional()`},`;
  });
  const body = `{\n${lines.join("\n")}\n}`;
  return extra === false ? `z.strictObject(${body})` : `z.looseObject(${body})`;
}

function arr(s: Schema): string {
  const items = s.items ? gen(s.items as Schema) : "z.unknown()";
  let z = `z.array(${items})`;
  if (typeof s.minItems === "number") z += `.min(${s.minItems})`;
  if (typeof s.maxItems === "number") z += `.max(${s.maxItems})`;
  return z;
}

function one(type: string, s: Schema): string {
  switch (type) {
    case "string": return str(s);
    case "integer": return num(s, true);
    case "number": return num(s, false);
    case "boolean": return "z.boolean()";
    case "null": return "z.null()";
    case "object": return obj(s);
    case "array": return arr(s);
    default: throw new Error(`unsupported type ${type}`);
  }
}

function gen(s: Schema): string {
  if (typeof s.$ref === "string") {
    const m = /^#\/\$defs\/([A-Za-z0-9_]+)$/.exec(s.$ref);
    if (!m) throw new Error(`unsupported $ref ${s.$ref}`);
    return `${m[1]}Schema`;
  }
  if (Array.isArray(s.enum)) return `z.enum(${JSON.stringify(s.enum)})`;
  const t = s.type;
  if (Array.isArray(t)) return `z.union([${(t as string[]).map((x) => one(x, s)).join(", ")}])`;
  if (typeof t === "string") return one(t, s);
  if (s.properties) return obj(s);
  return "z.unknown()";
}

const out: string[] = [
  "// Generated by scripts/gen_bundle_zod.ts from the AccountBundle JSON Schema. Do not edit;",
  "// run `npm run gen` after the schema changes.",
  'import { z } from "zod";',
  "",
];
for (const [name, def] of Object.entries(defs)) {
  defNames.push(name);
  out.push(`export const ${name}Schema = ${gen(def)};`, "");
}
out.push(`export const AccountBundleSchema = ${gen(root)};`, "");
out.push("export type AccountBundle = z.infer<typeof AccountBundleSchema>;", "");
writeFileSync(outPath, out.join("\n"));
console.log(`wrote ${outPath}`);
