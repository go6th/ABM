"""The exhaustion ladder (D-47; M6, M7, M9) and the upload request it raises.

"Our cap is reached" and "the provider says its balance is empty" are different classes with
different paths (M6): the cap path pauses for approval (``spend.pause``); this path never touches a
cap version and never consumes an approval.

**The ladder** (``decide``, pure, deterministic), when a provider reports its credits exhausted:

1. a valid registered pre-pulled file covering the operation is consumed (the connector does this
   before any paid call, at zero cost, ``route = prepulled``);
2. otherwise the first alternate route, in the configured fallback order, that the tenant policy
   allows (``allow_alternate_on_exhaustion``; default from ``spend.yaml`` ``v2``, D-47), that has
   an argument translation keeping the request's meaning, and whose circuit is not open; its result
   is labelled with its real route and graded from its real source tier (the router records
   ``route`` and ``fell_back_from``; the tracker still needs evidence for Done);
3. otherwise the affected rows are Blocked ``credits_exhausted`` (the failed call is their proof)
   and an upload request with the **exact file spec** is raised (``request_upload``).

``file_spec`` is generated by code from the pending operations (provider code, operation, the
exact arguments and their ledger hashes, the content type, the size cap, the account, the
attestations required); the operator's file must match it (``spend.upload``).

GUARANTEE(test_ladder_order_is_prepulled_then_alternate_then_upload): M7, property test.
GUARANTEE(test_exhaustion_never_touches_the_cap): M6.
GUARANTEE(test_upload_request_carries_the_exact_file_spec): M9.
"""

from __future__ import annotations

import hashlib
import json
import uuid
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from datetime import datetime, timedelta
from typing import Any, Literal
from uuid import UUID

from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncSession

from spend import notify
from spend.config import V2Config

NEW_KEY = "allow_alternate_on_exhaustion"
LEGACY_KEY = "allow_fallback_on_exhaustion"
Action = Literal["use_prepulled", "use_alternate", "block_and_request_upload"]


@dataclass(frozen=True)
class Alternate:
    """One configured alternate route and what is known about it now."""

    route: str
    provider_code: str
    operation: str
    translation: bool  # an argument translation that keeps the request's meaning exists
    circuit_open: bool
    exhausted: bool = False  # known exhausted in this run


@dataclass(frozen=True)
class Rung:
    """The ladder's decision."""

    action: Action
    alternate: Alternate | None
    reason: str


def alternate_allowed(policy: Mapping[str, Any] | None, default: bool) -> bool:
    """The tenant policy decides when it says so (either key, literal booleans only); otherwise
    the configured default (D-47)."""
    policy = policy or {}
    for key in (NEW_KEY, LEGACY_KEY):
        if isinstance(policy.get(key), bool):
            return bool(policy[key])
    return default


def decide(prepulled_valid: bool, alternates: Sequence[Alternate], tenant_allows: bool) -> Rung:
    """The first applicable rung (see the module docstring). Pure and deterministic."""
    if prepulled_valid:
        return Rung("use_prepulled", None, "a registered pre-pulled file covers the operation")
    if not tenant_allows:
        return Rung("block_and_request_upload", None, "tenant policy allows no alternate")
    for alt in alternates:
        if alt.exhausted:
            continue
        if alt.circuit_open:
            continue
        if not alt.translation:
            continue
        return Rung("use_alternate", alt, f"alternate route {alt.route}")
    return Rung("block_and_request_upload", None, "no usable alternate route")


async def tenant_alternate_allowed(s: AsyncSession, tenant_id: UUID, default: bool) -> bool:
    """``alternate_allowed`` over the tenant's stored policy (read under its own RLS context)."""
    policy = (
        await s.execute(text("SELECT policy_json FROM tenants WHERE id = :t"), {"t": tenant_id})
    ).scalar_one_or_none()
    return alternate_allowed(policy, default)


def file_spec(
    provider_code: str,
    operation: str,
    pending: Sequence[Mapping[str, Any]],
    account_domain: str,
    cfg: V2Config,
) -> dict[str, Any]:
    """The exact file an operator must supply (deterministic; hashed into the intent)."""
    calls: list[dict[str, Any]] = [
        {"args_hash": str(p["args_hash"]), "args": dict(p["args"])} for p in pending
    ]
    calls.sort(key=lambda c: str(c["args_hash"]))
    return {
        "provider_code": provider_code,
        "operation": operation,
        "format": "the provider's own response body for this operation, unmodified",
        "content_types": sorted(cfg.upload_content_types),
        "max_bytes": cfg.upload_max_bytes,
        "pending_calls": calls,
        "account_domain": account_domain,
        "attestations_required": ["account", "pull_date"],
        "max_age_days": cfg.upload_max_age_days,
        "parser": f"{provider_code}.{operation} (the same strict normaliser as a live response)",
    }


def spec_hash(spec: Mapping[str, Any]) -> str:
    """sha256 of the canonical spec."""
    return hashlib.sha256(
        json.dumps(spec, sort_keys=True, separators=(",", ":")).encode()
    ).hexdigest()


async def request_upload(
    s: AsyncSession,
    tenant_id: UUID,
    run_id: UUID,
    cap_version: int,
    spec: Mapping[str, Any],
    now: datetime,
    cfg: V2Config,
) -> UUID:
    """Record the exhaustion and the upload request (an intent with its spec), once per spec, and
    notify the operator. In the caller's transaction; never touches a cap version (M6)."""
    digest = spec_hash(spec)
    existing = (
        await s.execute(
            text("SELECT id FROM prepulled_intents WHERE run_id = :r AND spec_hash = :h"),
            {"r": run_id, "h": digest},
        )
    ).scalar_one_or_none()
    if existing is not None:
        return UUID(str(existing))
    intent = uuid.uuid4()
    key = f"quarantine/{tenant_id}/{run_id}/{intent}"
    await s.execute(
        text(
            "INSERT INTO prepulled_intents (id, run_id, provider_code, operation, spec_json,"
            " spec_hash, quarantine_key, created_by, expires_at, created_at)"
            " VALUES (:i, :r, :p, :o, CAST(:s AS jsonb), :h, :k, 'system', :exp, :at)"
        ),
        {
            "i": intent,
            "r": run_id,
            "p": spec["provider_code"],
            "o": spec["operation"],
            "s": json.dumps(spec, sort_keys=True),
            "h": digest,
            "k": key,
            "exp": now + timedelta(minutes=cfg.upload_intent_ttl_minutes),
            "at": now,
        },
    )
    await s.execute(
        text(
            "INSERT INTO prepulled_intent_events (intent_id, event, at) VALUES (:i, 'created', :at)"
        ),
        {"i": intent, "at": now},
    )
    for event in ("exhausted", "upload_requested"):
        await s.execute(
            text(
                "INSERT INTO spend_limit_events (run_id, cap_version, event, detail_json, at)"
                " VALUES (:r, :v, :e, CAST(:d AS jsonb), :at)"
            ),
            {
                "r": run_id,
                "v": cap_version,
                "e": event,
                "d": json.dumps({"provider_code": spec["provider_code"], "intent_id": str(intent)}),
                "at": now,
            },
        )
    await notify.enqueue(
        s,
        run_id,
        f"exhausted:{run_id}:{digest[:16]}",
        "operator",
        "provider_credits_exhausted",
        {"run_id": str(run_id), "provider_code": spec["provider_code"], "intent_id": str(intent)},
        now,
    )
    return intent
