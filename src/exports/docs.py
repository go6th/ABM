"""Generate ``docs/exports/theme.md`` and ``docs/exports/files.md`` from the configuration so the
documents cannot drift. ``python -m exports.docs --check`` exits 1 when a file is stale (a test
runs it)."""

from __future__ import annotations

import sys
from pathlib import Path

from exports.config import ExportConfig, load_export_config

ROOT = Path(__file__).resolve().parents[2]
THEME = ROOT / "docs/exports/theme.md"
FILES = ROOT / "docs/exports/files.md"
_HEAD = "<!-- Generated by `python -m exports.docs`; do not edit by hand. -->\n\n"


def render_theme(cfg: ExportConfig) -> str:
    """The look, value by value, with its status and source."""
    t = cfg.theme
    w, x = t.word, t.excel
    out = [
        _HEAD + "# Export theme (the look)",
        "",
        f"Status: **{t.status}** ({t.decision}). Source: {t.source}.",
        f"Theme hash recorded on every deliverable: `{cfg.theme_hash}`.",
        "",
        "Every value below is a labelled proposal until the legacy Node docx library, the two",
        "workbook scripts and one real delivered file set are supplied; each value is then",
        "replaced by the legacy value and its source names the file and line.",
        "",
        "## Word",
        "",
        f"Page {w.page.width_in} by {w.page.height_in} inches; margins top {w.page.margins_in.top},"
        f" bottom {w.page.margins_in.bottom}, left {w.page.margins_in.left}, right"
        f" {w.page.margins_in.right} inches ({w.page.source}).",
        "",
        "| Role | Font | Size (pt) | Bold | Italic | Colour |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for role, f in w.fonts.model_dump().items():
        out.append(
            f"| {role} | {f['name']} | {f['size_pt']} | {f['bold']} | {f['italic']} |"
            f" {f['color']} |"
        )
    out += [
        "",
        f"Tables: header fill {w.table.header_fill}, border {w.table.border_color} at"
        f" {w.table.border_size_eighth_pt}/8 pt, cell margin {w.table.cell_margin_twips} twips,"
        f" header row repeated: {w.table.repeat_header_row}, rows never split across pages:"
        f" {w.table.row_cant_split}.",
        "",
        "| Table | Column proportions (percent) |",
        "| --- | --- |",
    ]
    for name, widths in w.tables.items():
        out.append(f"| {name} | {', '.join(f'{v:g}' for v in widths)} |")
    out += [
        "",
        "## Workbooks",
        "",
        "| Role | Font | Size (pt) | Bold | Italic | Colour |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for role, f in x.fonts.model_dump().items():
        out.append(
            f"| {role} | {f['name']} | {f['size_pt']} | {f['bold']} | {f['italic']} |"
            f" {f['color']} |"
        )
    out += [
        "",
        f"Header fill {x.header_fill}, summary fill {x.summary_fill}, border {x.border_color};"
        f" frozen header: {x.freeze_header}; filter: {x.autofilter}; print"
        f" {x.print.orientation} on {x.print.paper}, fit to width: {x.print.fit_to_width}.",
        "",
        "| Column kind | Width | Number format | Wrap |",
        "| --- | --- | --- | --- |",
    ]
    for kind, s in x.column_kinds.items():
        out.append(f"| {kind} | {s.width:g} | `{s.number_format}` | {s.wrap} |")
    out += ["", f"Packages: {t.zip.compression}, fixed entry time {t.zip.entry_time}.", ""]
    return "\n".join(out)


def render_files(cfg: ExportConfig) -> str:
    """The file set: names, contents, columns and the provenance of each decision."""
    r = cfg.rules
    out = [
        _HEAD + "# The standing file set",
        "",
        f"Rules status: **{r.status}** ({r.decision}); rules hash `{cfg.rules_hash}` (covers",
        "`export_rules.yaml`, `lanes.yaml` and `output_spec.yaml`).",
        "",
        "| Kind | File name | Format |",
        "| --- | --- | --- |",
    ]
    for kind in ("summary", "evidence", "people", "jobs", "tech", "workspace"):
        ext = {"summary": "docx", "evidence": "docx", "workspace": "zip"}.get(kind, "xlsx")
        out.append(f"| {kind} | `{cfg.filenames[kind]}.{ext}` | {ext} |")
    out += ["", "## Account Summary sections (PRD order)", "", f"Source: {r.headings.source}.", ""]
    out += [f"{i}. {h}" for i, h in enumerate(r.headings.summary.model_dump().values(), start=1)]
    out += [
        "",
        "## Word tables",
        "",
        f"Source: {r.documents.source}.",
        "",
        "| Table | Headers |",
        "| --- | --- |",
    ]
    for name, headers in r.documents.tables.items():
        out.append(f"| {name} | {', '.join(headers)} |")
    out += ["", "## Workbook columns", "", f"Source: {r.workbooks.source}.", ""]
    tech = r.workbooks.tech
    sheets = (
        (r.workbooks.people.sheet, r.workbooks.people.columns),
        (r.workbooks.jobs.sheet, r.workbooks.jobs.columns),
        (tech.ranking_sheet, tech.ranking_columns),
        (tech.sheet, tech.columns),
    )
    for sheet, columns in sheets:
        out += [f"### {sheet}", "", "| Key | Header | Kind |", "| --- | --- | --- |"]
        out += [f"| {c.key} | {c.header} | {c.kind} |" for c in columns]
        out.append("")
    out += [
        f"Other sheets: People `{r.workbooks.people.summary_sheet}`; Job Postings"
        f" `{r.workbooks.jobs.summary_sheet}` first (title, paragraphs and the platform matrix,"
        f" platforms {', '.join(r.workbooks.jobs.matrix_platforms)}), then"
        f" `{r.workbooks.jobs.counts_sheet}` (count lines) and"
        f" `{r.workbooks.jobs.long_text_sheet}`; Tech Stack `{tech.teams_sheet}` (columns"
        f" {', '.join(c.header for c in tech.teams_columns)}; no team records are stored yet).",
        "",
        f"Platform dictionary: {len(cfg.platforms)} platforms; out-of-scope platforms masked:"
        f" {len(cfg.scope.never_report)} (mask `{cfg.scope.mask}`).",
        "",
    ]
    ws = r.workspace
    dashes, partner = r.banned_dashes, r.partner_rule
    out += [
        "## Workspace zip (D-25)",
        "",
        f"Status: {ws.status}. Members in order: RESTORE.md (built from the run), MANIFEST.json,",
        f"then the folders {', '.join(f'`{f}/`' for f in ws.folders)}: the five deliverables,",
        "the render data of each file under `build/`, and the run's own records",
        f"({', '.join(f'`{n}`' for n in ws.required_members)}), each built from stored",
        "rows only and required by the zip check. Raw payloads:",
        f"{ws.raw_payloads.default} (neutral-name copy enabled:"
        f" {ws.raw_payloads.neutral_name_copy_enabled}); organisation-provider payloads never.",
        f"Caps: {ws.max_members} members, {ws.max_member_bytes} bytes per member,"
        f" {ws.max_total_bytes} bytes in total, names up to {ws.entry_name_max} characters.",
        f"RESTORE.md wording: {ws.restore_text_source}.",
        "",
        "## Content rules (D-24)",
        "",
        f"* Banned dashes ({dashes.scope}): {len(dashes.characters)} characters"
        f" ({dashes.characters_source}); spaced hyphen as punctuation:"
        f" {dashes.spaced_hyphen_is_punctuation} ({dashes.spaced_hyphen_status}).",
        f"* Stale phrases: {len(r.stale_phrases.phrases)} listed ({r.stale_phrases.source}).",
        f"* Abbreviations: {len(r.abbreviations.entries)} listed ({r.abbreviations.source}).",
        f"* Partner framings: {', '.join(partner.framings)} ({partner.framings_source});"
        f" more: {partner.more_framings_source}.",
        f"* Restricted term in a verbatim quote: {r.quote_handling.policy}"
        f" ({r.quote_handling.status}).",
        f"* Excel cell limit: {r.limits.excel_cell_chars} ({r.limits.excel_cell_chars_source}).",
        f"* Row caps ({r.limits.row_caps_status}): "
        + ", ".join(f"{k} {v}" for k, v in r.limits.row_caps.model_dump().items())
        + ".",
        "",
    ]
    return "\n".join(out)


def main(argv: list[str]) -> int:
    """Write both documents, or with ``--check`` exit 1 when either is stale."""
    cfg = load_export_config()
    pairs = ((THEME, render_theme(cfg)), (FILES, render_files(cfg)))
    if "--check" in argv:
        stale = [p for p, body in pairs if not p.exists() or p.read_text() != body]
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)}")
        return 1 if stale else 0
    for path, body in pairs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body)
    return 0


if __name__ == "__main__":  # pragma: no cover - command line entry
    sys.exit(main(sys.argv[1:]))
