"""Lessons as code (D-99, G12).

Every entry of the archive's ``lessons.md`` (guide S8: dated sections 2026-09-20 to 2026-09-29,
corrections written as general rules) becomes a rule in ``config/lessons.yaml`` with:

* ``id`` (``L-YYYYMMDD-n``), ``source`` (``lessons.md:<line>``), ``date`` and the ``rule`` text as
  written in the archive;
* ``enforcement``: ``code`` (a guard id G1..G17 in ``guard``), ``prompt`` (the agent whose prompt
  carries the rule, tagged with the lesson id) or ``process`` (no automatable guard; flagged);
* ``test``: the name of a test function under ``tests/agents``.

``parse_lessons_md`` reads the archive file. Its format is assumed to be ``## YYYY-MM-DD``
headings with ``-`` or ``*`` bullets ([VERIFY] against the archive, docs/open-items.md).
``lessons_check`` returns ``ok``, ``failed`` (a lesson without a valid guard or test) or
``incomplete`` (the archive is absent, so no lesson could be loaded: never reported as ok).

GUARANTEE(test_lessons_check_fails_without_guard_or_test)
GUARANTEE(test_lessons_check_is_incomplete_while_the_archive_is_absent)
"""

from __future__ import annotations

import re
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Literal

from agents.contracts import GUARD_IDS

_HEADING = re.compile(r"^#{2,3}\s+(\d{4}-\d{2}-\d{2})\b")
_BULLET = re.compile(r"^\s*[-*]\s+(.+?)\s*$")
_ID = re.compile(r"^L-\d{8}-\d+$")
_SOURCE = re.compile(r"^lessons\.md:\d+$")
ENFORCEMENTS = frozenset({"code", "prompt", "process"})


@dataclass(frozen=True)
class LessonEntry:
    """One lesson as read from the archive."""

    id: str
    date: str
    line: int
    rule: str


def parse_lessons_md(text: str) -> list[LessonEntry]:
    """Bullets under dated headings, numbered per date, with their 1-based line numbers."""
    out: list[LessonEntry] = []
    date: str | None = None
    counts: dict[str, int] = {}
    for number, raw in enumerate(text.splitlines(), start=1):
        heading = _HEADING.match(raw)
        if heading:
            date = heading.group(1)
            continue
        bullet = _BULLET.match(raw)
        if bullet and date:
            counts[date] = counts.get(date, 0) + 1
            out.append(
                LessonEntry(
                    f"L-{date.replace('-', '')}-{counts[date]}", date, number, bullet.group(1)
                )
            )
    return out


def generate_entries(entries: Iterable[LessonEntry]) -> list[dict[str, Any]]:
    """``config/lessons.yaml`` entries: enforcement ``process`` and a test name to be written."""
    return [
        {
            "id": e.id,
            "date": e.date,
            "source": f"lessons.md:{e.line}",
            "rule": e.rule,
            "enforcement": "process",
            "guard": None,
            "test": f"test_lesson_{e.id.replace('-', '_').lower()}",
        }
        for e in entries
    ]


def stub_tests(entries: Sequence[Mapping[str, Any]]) -> str:
    """A test module with one test per lesson that fails until the lesson has a guard."""
    lines = [
        '"""Generated by scripts/abm_lessons.py: one test per lesson (D-99). Replace each body',
        'with a test of the lesson\'s guard; a lesson left as ``process`` fails here."""',
        "",
        "from agents.lessons import require_guard",
        "",
    ]
    for e in entries:
        lines += ["", f"def {e['test']}() -> None:", f"    require_guard({e['id']!r})", ""]
    return "\n".join(lines)


def require_guard(lesson_id: str, lessons: Sequence[Mapping[str, Any]] | None = None) -> None:
    """Fail unless the lesson is enforced by a known guard or a tagged prompt."""
    from agents.config import load_skill_config

    found = [e for e in (lessons or load_skill_config().lessons) if e.get("id") == lesson_id]
    if not found:
        raise AssertionError(f"{lesson_id}: not in config/lessons.yaml")
    problem = entry_problem(found[0], prompts_dir=Path(__file__).parent)
    if problem:
        raise AssertionError(f"{lesson_id}: {problem}")


def entry_problem(entry: Mapping[str, Any], prompts_dir: Path) -> str | None:
    """Why one lesson is not enforced (None when it is)."""
    if not _ID.match(str(entry.get("id", ""))):
        return "bad_id"
    if not _SOURCE.match(str(entry.get("source", ""))):
        return "no_dated_source_line"
    if not entry.get("rule"):
        return "no_rule_text"
    enforcement = entry.get("enforcement")
    if enforcement not in ENFORCEMENTS:
        return "unknown_enforcement"
    if enforcement == "process":
        return "process_only"
    if enforcement == "code" and entry.get("guard") not in GUARD_IDS:
        return "no_guard"
    if enforcement == "prompt":
        prompt = prompts_dir / str(entry.get("guard")) / "prompt.md"
        if not prompt.is_file() or f"[{entry['id']}]" not in prompt.read_text():
            return "prompt_not_tagged"
    return None


@dataclass(frozen=True)
class LessonsReport:
    """The check's verdict and every problem by lesson id."""

    status: Literal["ok", "failed", "incomplete"]
    problems: tuple[tuple[str, str], ...]
    checked: int


def defined_tests(tests_dir: Path) -> frozenset[str]:
    """Names of test functions defined under ``tests_dir``."""
    names: set[str] = set()
    for path in tests_dir.rglob("test_*.py"):
        names |= set(re.findall(r"^\s*(?:async\s+)?def\s+(test_\w+)", path.read_text(), re.M))
    return frozenset(names)


def lessons_check(
    lessons: Sequence[Mapping[str, Any]],
    archive_status: str,
    tests_dir: Path,
    prompts_dir: Path,
) -> LessonsReport:
    """See the module docstring."""
    problems: list[tuple[str, str]] = []
    seen: set[str] = set()
    tests = defined_tests(tests_dir)
    for entry in lessons:
        lesson_id = str(entry.get("id"))
        if lesson_id in seen:
            problems.append((lesson_id, "duplicate_id"))
        seen.add(lesson_id)
        problem = entry_problem(entry, prompts_dir)
        if problem:
            problems.append((lesson_id, problem))
        if entry.get("test") not in tests:
            problems.append((lesson_id, "no_test"))
    if problems:
        return LessonsReport("failed", tuple(problems), len(lessons))
    if archive_status != "present" or not lessons:
        return LessonsReport("incomplete", (("*", f"archive_{archive_status}"),), len(lessons))
    return LessonsReport("ok", (), len(lessons))
