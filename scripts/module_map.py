"""Generate docs/architecture/module-map.md: every first-party package, what it imports, cycles.

Static analysis of import statements (ast); run: python scripts/module_map.py [--check]
"""

from __future__ import annotations

import ast
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
OUT = ROOT / "docs" / "architecture" / "module-map.md"
FIRST_PARTY = ("account_intelligence", "jobs")


def package_of(module: str) -> str:
    """Group modules at the second level (account_intelligence.grading) or first (jobs)."""
    parts = module.split(".")
    return ".".join(parts[:2]) if parts[0] == "account_intelligence" and len(parts) > 1 else parts[0]


def module_name(path: Path) -> str:
    rel = path.relative_to(SRC).with_suffix("")
    parts = list(rel.parts)
    if parts[-1] == "__init__":
        parts = parts[:-1]
    return ".".join(parts)


def imports_of(path: Path, current: str) -> set[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    found: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            found.update(a.name for a in node.names)
        elif isinstance(node, ast.ImportFrom):
            if node.level:
                base = current.split(".")[: -node.level] if not path.name == "__init__.py" else current.split(".")[: len(current.split(".")) - node.level + 1]
                found.add(".".join([*base, node.module] if node.module else base))
            elif node.module:
                found.add(node.module)
                # "from pkg import mod" imports pkg.mod when mod is a submodule
                found.update(f"{node.module}.{a.name}" for a in node.names)
    return {m for m in found if m.split(".")[0] in FIRST_PARTY}


def build() -> tuple[dict[str, set[str]], list[list[str]], list[str]]:
    edges: dict[str, set[str]] = defaultdict(set)
    modules = {module_name(p): p for p in SRC.rglob("*.py")}
    imported: set[str] = set()
    for name, path in modules.items():
        for target in imports_of(path, name):
            imported.add(target)
            a, b = package_of(name), package_of(target)
            if a != b:
                edges[a].add(b)
            edges.setdefault(b, set())
    cycles: list[list[str]] = []
    for a in sorted(edges):
        for b in sorted(edges[a]):
            if a in edges.get(b, set()) and a < b:
                cycles.append([a, b])
    orphans = sorted(
        n for n in modules
        if n not in imported and not n.endswith(("__init__", "__main__"))
        and not any(i.startswith(n + ".") for i in imported)
        and n.split(".")[-1] not in ("main", "docs") and "api" not in n.split(".")
    )
    return edges, cycles, orphans


def render() -> str:
    edges, cycles, orphans = build()
    lines = ["# Module map (generated by scripts/module_map.py; do not edit)", "",
             "| Package | Imports (first-party packages) |", "|---|---|"]
    for pkg in sorted(edges):
        lines.append(f"| `{pkg}` | {', '.join(f'`{d}`' for d in sorted(edges[pkg])) or '-'} |")
    lines += ["", "## Package-level cycles", ""]
    lines += [f"* `{a}` <-> `{b}`" for a, b in cycles] or ["None."]
    lines += ["", "## Modules no first-party module imports (entry points, scripts or dead code)", ""]
    lines += [f"* `{o}`" for o in orphans] or ["None."]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    content = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == content else 1)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(content)
    print(content)
