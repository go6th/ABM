"""Generate docs/jobs/rubric.md and docs/jobs/counts.md (never edited by hand).

``rubric.md`` comes from ``config/posting_rubric.yaml`` and ``config/job_lanes.yaml``;
``counts.md`` from the ``jobs.counts`` module docstring (the contract lives with the code).
Usage: ``python scripts/gen_jobs_docs.py`` writes; ``--check`` exits 1 when either is stale.
"""

from __future__ import annotations

import ast
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs/jobs"


def rubric() -> str:
    """Class rules, full-text scope and lanes, with their status and source."""
    r = yaml.safe_load((ROOT / "config/posting_rubric.yaml").read_text())
    lanes = yaml.safe_load((ROOT / "config/job_lanes.yaml").read_text())
    out = [
        "# Posting classification rubric (decision D-16, proposal)",
        "",
        "Generated by `scripts/gen_jobs_docs.py` from `config/posting_rubric.yaml` and"
        " `config/job_lanes.yaml`; do not edit by hand. Every rule is a proposal derived from the"
        " class names only; cues match whole words in the description, never the title alone.",
        "",
        "| Rule | Class | Cues | Positive example | Negative example | Status |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for rule in r["rules"]:
        out.append(
            f"| `{rule['rule_id']}` | {rule['label']} | {', '.join(rule['cues'])} |"
            f" {rule['positive']} | {rule['negative']} | {rule['status']} |"
        )
    scope = r["full_text_required_classes"]
    out += [
        "",
        f"Full text required for: {', '.join(scope['value'])} ({scope['status']};"
        f" {scope['source']}).",
        "",
        "## Lanes and platform lexicon (decision D-17)",
        "",
        "| Lane | Platforms | Aliases | Keywords |",
        "| --- | --- | --- | --- |",
    ]
    fallback = lanes["keyword_fallback"]
    for lane in lanes["lanes"]:
        names = [p["name"] for p in lane["platforms"]] or ["none (needs product owner)"]
        aliases = [a for p in lane["platforms"] for a in p.get("aliases") or []] or ["none"]
        keywords = lane["keywords"] or [f"fallback: {fallback['value']} ({fallback['status']})"]
        out.append(
            f"| {lane['label']} | {', '.join(names)} | {', '.join(aliases)} |"
            f" {', '.join(keywords)} |"
        )
    return "\n".join(out) + "\n"


def counts() -> str:
    """The counts contract from the module docstring."""
    tree = ast.parse((ROOT / "src/jobs/counts.py").read_text())
    doc = ast.get_docstring(tree) or ""
    return (
        "# Job posting count contract\n\nGenerated by `scripts/gen_jobs_docs.py` from the"
        " `jobs.counts` module docstring; do not edit by hand.\n\n" + doc + "\n"
    )


def main(argv: list[str]) -> int:
    """Write or check both documents."""
    stale = []
    for name, text in (("rubric.md", rubric()), ("counts.md", counts())):
        path = DOCS / name
        if "--check" in argv:
            if path.read_text() != text:
                stale.append(name)
        else:
            path.write_text(text)
    if stale:
        print(f"stale: {stale}; run python scripts/gen_jobs_docs.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
