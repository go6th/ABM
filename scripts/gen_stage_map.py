"""Generate docs/workflow/stage-map.md from config (the doc is never edited by hand).

Usage: ``python scripts/gen_stage_map.py`` writes the file; ``--check`` exits 1 when the file
on disk differs from what the config produces (used by tests and CI).
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs/workflow/stage-map.md"

HEADER = """# Workflow v1 coverage ownership

Generated by `scripts/gen_stage_map.py` from `config/workflow_v1.yaml` and
`config/checklist.yaml`; do not edit by hand. Row keys are the canonical keys of the skill's
`assets/checklist.yaml` (one key space, finding SC-1); the `P` id is the PRD Appendix A
reference. The original PRD Appendix A is not in `docs/sources/`, so owners marked
**proposed** need product-owner confirmation.

| Key | Appendix A id | Checklist row | Pass | Priority | Owner | Basis |
| --- | --- | --- | ---: | --- | --- | --- |
"""

FOOTER = """
Every checklist row has exactly one configured owner (enforced by `workflow.spec.load_spec`
and `tests/workflow/test_stage_map.py`). `setup`, `distill_grade`, `build`, `gate` and
`deliver` own no discovery rows; they govern run setup, grading, output generation,
validation and delivery.
"""


def render() -> str:
    """Return the markdown the config implies."""
    workflow = yaml.safe_load((ROOT / "config/workflow_v1.yaml").read_text())
    rows = yaml.safe_load((ROOT / "config/checklist.yaml").read_text())["rows"]
    owner = {key: s["id"] for s in workflow["stages"] for key in s.get("coverage", [])}
    basis = workflow["coverage_basis"]
    lines = []
    for row in rows:
        key = row["key"]
        flag = " **proposed**" if basis[key]["proposed"] else ""
        lines.append(
            f"| `{key}` | {row['id']} | {row['row']} | {row['pass']} |"
            f" {str(row['priority']).lower()} | `{owner[key]}`{flag} | {basis[key]['basis']} |"
        )
    return HEADER + "\n".join(lines) + "\n" + FOOTER


def main(argv: list[str]) -> int:
    """Write or check the generated document."""
    text = render()
    if "--check" in argv:
        if OUT.read_text() != text:
            print("stale: run python scripts/gen_stage_map.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
