#!/usr/bin/env python3
"""Generate ``docs/ENVIRONMENT.md`` from the typed registry (``account_intelligence.config``).

Lists every environment variable by name with its purpose, whether it is a secret, and where it
is required or forbidden. No values are ever written. Variables read outside the Python services
(the web server, tests and CI, the local fake IdP) and retired variables are listed here by hand.
``--check`` exits 1 when the committed file differs from the generated one.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from account_intelligence.config import registry  # noqa: E402

OUT = ROOT / "docs" / "ENVIRONMENT.md"

# (name, purpose, secret)
WEB = [
    ("API_ORIGIN", "Server-side origin of the API the web server proxies /v1 to.", False),
    ("NEXT_DIST_DIR", "Next.js build output directory (defaults to .next).", False),
    ("OPERATOR_GOOGLE_CLIENT_ID", "Google OAuth client id of the staff console.", False),
    ("OPERATOR_GOOGLE_CLIENT_SECRET", "Google OAuth client secret of the staff console.", True),
    ("OPERATOR_GOOGLE_REDIRECT_URI", "Exact OAuth redirect URI of the staff console.", False),
    ("NODE_ENV", "Node runtime mode (set to production by the image).", False),
]
TOOLING = [
    ("TEST_DB", "Name of the scratch test database (tests create and drop it).", False),
    ("ADMIN_DSN", "Superuser DSN of the test database (tests, tooling).", True),
    (
        "ADMIN_MAINT_DSN",
        "Superuser DSN of the maintenance database (tests create databases).",
        True,
    ),
    ("APP_DSN", "Runtime-role DSN of the test database (tests).", True),
    ("PGPASSWORD", "Local Postgres superuser password for tooling (local stack only).", True),
    ("PG_CONTAINER", "CI Postgres service container id for the backup/restore test.", False),
    ("E2E_SLUG_A", "Set by the E2E harness: synthetic tenant A's sign-in slug.", False),
    ("E2E_SLUG_B", "Set by the E2E harness: synthetic tenant B's sign-in slug.", False),
    ("E2E_WEB_ORIGIN", "Web origin the E2E harness redirects to.", False),
    ("E2E_API_ORIGIN", "API origin used by the Playwright harness.", False),
    ("E2E_API_PORT", "Local port for the synthetic E2E API server.", False),
    ("PARITY_WEB_ORIGIN", "Web origin for the parity Playwright suite.", False),
    ("SCREENS", "Optional selection of review screenshots to capture.", False),
    ("FAKE_IDP_ISSUER", "Issuer of the local fake IdP (local stack only).", False),
    ("FAKE_IDP_AUDIENCE", "Audience the local fake IdP mints tokens for.", False),
    ("TF_STATE_BUCKET", "GCS bucket of the Terraform remote state (deploy pipeline).", False),
]
RETIRED = [
    ("ENV", "Duplicate of APP_ENV; never read."),
    ("SLICE_SECONDS", "Slice length comes from config/workflow_v1.yaml; never read."),
    ("MAX_SLICES", "Slice cap comes from config/workflow_v1.yaml; never read."),
    ("TENANT_CONCURRENCY", "Concurrency comes from config/parallel.yaml; never read."),
    ("OBJECT_STORE_ENDPOINT", "S3-compatible store replaced by Cloud Storage; never read."),
    ("OBJECT_STORE_BUCKET", "Replaced by PAYLOAD_BUCKET; never read."),
    ("OBJECT_STORE_ACCESS_KEY", "S3-compatible store replaced by Cloud Storage; never read."),
    ("OBJECT_STORE_SECRET_KEY", "S3-compatible store replaced by Cloud Storage; never read."),
    ("OBJECT_STORE_REGION", "S3-compatible store replaced by Cloud Storage; never read."),
]


def _yes(flag: bool) -> str:
    return "**secret**" if flag else "no"


def render() -> str:
    """The whole document."""
    lines = [
        "# Environment variables",
        "",
        "Generated by `scripts/gen_env_docs.py` from the typed registry in",
        "`src/account_intelligence/config.py`; do not edit by hand. Names only: no value appears",
        "here or in any committed file. `make env-check` validates the current environment.",
        "",
        "Where values live:",
        "",
        "- **Local:** the ignored `.env` file (mode 600). The default `make up` stack is hermetic",
        "  and reads none of it; `compose.live.yml` opts in to real keys.",
        "- **Google Cloud:** every secret is a Secret Manager secret referenced by Cloud Run",
        "  (`value_source.secret_key_ref`). Terraform creates the secret containers only; values",
        "  are added out of band, so no secret is in an image, a Terraform variable or state.",
        "",
        "Profiles: `dev`, `test` (local) and `staging`, `production` (cloud). A process refuses",
        "to start when a variable required for its profile is missing, a forbidden one is set,",
        "or a value has the wrong type (errors name the variable, never the value).",
        "",
        "## Services (API, worker, run job, migrations)",
        "",
        "| Variable | Purpose | Secret | Required in | Forbidden in | Used by |",
        "|---|---|---|---|---|---|",
    ]
    for row in registry():
        lines.append(
            f"| `{row['name']}` | {row['purpose']} | {_yes(row['secret'])} |"
            f" {', '.join(row['required_in']) or '-'} | {', '.join(row['forbidden_in']) or '-'} |"
            f" {row['component']} |"
        )
    lines += ["", "## Web server", "", "| Variable | Purpose | Secret |", "|---|---|---|"]
    lines += [f"| `{n}` | {p} | {_yes(s)} |" for n, p, s in WEB]
    lines += ["", "## Tests, CI and local tooling", "", "| Variable | Purpose | Secret |"]
    lines += ["|---|---|---|"] + [f"| `{n}` | {p} | {_yes(s)} |" for n, p, s in TOOLING]
    lines += [
        "",
        "## Retired (no code reads them; safe to delete from a local `.env`)",
        "",
        "| Variable | Why |",
        "|---|---|",
    ]
    lines += [f"| `{n}` | {why} |" for n, why in RETIRED]
    return "\n".join(lines) + "\n"


def names() -> set[str]:
    """Every documented variable name."""
    return (
        {r["name"] for r in registry()}
        | {n for n, _, _ in WEB}
        | {n for n, _, _ in TOOLING}
        | {n for n, _ in RETIRED}
    )


def main(argv: list[str]) -> int:
    """Write the document, or with ``--check`` compare it."""
    text = render()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("docs/ENVIRONMENT.md is stale: run python scripts/gen_env_docs.py")
            return 1
        print("docs/ENVIRONMENT.md is current")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
