"""Generate ``web/lib/parity/tableSpecs.ts`` from ``parity.tables`` (the one table definition).

    uv run python scripts/parity/gen_table_specs.py [--check]

``--check`` exits 1 when the committed file differs from what the specs produce (the test
``tests/parity/test_tables.py`` runs it).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

from parity import tables as T  # noqa: E402

OUT = ROOT / "web" / "lib" / "parity" / "tableSpecs.ts"
HEADER = """\
// GENERATED by scripts/parity/gen_table_specs.py from src/parity/tables.py (never edited).
// The tables of the delivered files: id, file, sheet or title, columns (key, header, kind,
// link label, chip fills) and whether the table pages on the server. The header placeholder
// "{pull_day_month}" is filled by the API with the bundle's pull date.

export type ColumnKind =
  | "text" | "long" | "num" | "link" | "priority" | "rank" | "grade" | "status" | "id";

export interface ParityColumnSpec {
  key: string;
  header: string;
  kind: ColumnKind;
  link_label: string | null;
  fills: Record<string, string> | null;
}

export interface ParityTableSpec {
  id: string;
  file: string;
  sheet: string | null;
  title: string;
  paginated: boolean;
  columns: ParityColumnSpec[];
}

"""


def render() -> str:
    """The TypeScript module text."""
    specs = [T.spec_json(t) for t in T.TABLES]
    part_c = {
        "id": T.PART_C_PREFIX + "{lane}",
        "file": "evidence",
        "sheet": None,
        "title": "Part C: {lane}",
        "paginated": False,
        "columns": T.spec_json(T.TableSpec("part_c", "evidence", "Part C", T.PART_C_COLUMNS))[
            "columns"
        ],
    }
    files = {k: {"suffix": v, "label": T.FILE_LABELS[k]} for k, v in T.FILE_SUFFIX.items()}
    dumps = lambda v: json.dumps(v, indent=2, ensure_ascii=False)  # noqa: E731
    lines = [
        "export const FILES: Record<string, { suffix: string; label: string }> = "
        + dumps(files)
        + ";",
        "",
        f"export const FILE_ORDER: readonly string[] = {json.dumps(list(T.FILES))};",
        "",
        f"export const PART_C_PREFIX = {json.dumps(T.PART_C_PREFIX)};",
        "",
        f"export const PART_C_TABLE: ParityTableSpec = {dumps(part_c)};",
        "",
        f"export const TABLE_SPECS: readonly ParityTableSpec[] = {dumps(specs)};",
        "",
        "export const TABLE_BY_ID: Record<string, ParityTableSpec> = "
        "Object.fromEntries(TABLE_SPECS.map((t) => [t.id, t]));",
        "",
        f"export const PRIORITY_FILLS: Record<string, string> = {json.dumps(T.PRIORITY_FILLS)};",
        f"export const RANK_FILLS: Record<string, string> = {json.dumps(T.RANK_FILLS)};",
        f"export const PAGE_LIMIT_DEFAULT = {T.PAGE_LIMIT_DEFAULT};",
        f"export const PAGE_LIMIT_MAX = {T.PAGE_LIMIT_MAX};",
    ]
    body = "\n".join(lines) + "\n"
    return HEADER + body


def main(argv: list[str] | None = None) -> int:
    """Write the module, or check it."""
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is out of date; run scripts/parity/gen_table_specs.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
