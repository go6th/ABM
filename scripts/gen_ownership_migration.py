"""Write migration 0063 (private workspaces) from ``config/ownership.yaml``.

For every owned table: add ``owner_user_id`` where missing, give existing rows their owner (the
``from`` rule, else the client's first user, else ``system:unowned`` for a client with no user),
make it NOT NULL with the transaction's user as default, index it tenant first, and replace the
table's app_rw policy with tenant AND owner. Accounts become unique per owner and domain. The
down file reverses each step. ``--check`` fails when the committed files differ from what this
script writes.

Usage: ``uv run python scripts/gen_ownership_migration.py [--check]``
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "config" / "ownership.yaml"
UP = ROOT / "migrations" / "0063_private_workspaces.sql"
DOWN = ROOT / "migrations" / "0063_private_workspaces.down.sql"
UNOWNED = "system:unowned"
TENANT = "tenant_id = (SELECT app_tenant())"
OWNER = "(owner_user_id = (SELECT app_user()) OR (SELECT app_scope()) = 'system')"
# Policies whose app_rw name is not ``tenant_isolation`` (from the catalogue, migration 0032).
POLICY_NAMES = {
    "coverage_rows": "tenant_isolation_coverage_rows",
    "coverage_row_events": "tenant_isolation_coverage_row_events",
    "run_coverage_meta": "tenant_isolation_run_coverage_meta",
}

HEADER = """-- Private workspaces (owner decision 2026-10-14, Phase 4B section 7). GENERATED by
-- scripts/gen_ownership_migration.py from config/ownership.yaml; edit those, not this file.
--
-- app.user_id sits next to app.tenant_id in every transaction (db.session.tenant_txn). A row of
-- an owned table is visible and writable only inside its own tenant AND to its own user, or to a
-- system job (app.scope = 'system': scheduler ticks, the sweeper, the isolation check, operator
-- counts). With neither a user nor the system scope, owned rows are invisible (fail closed).
"""


def _owner_expr(table: str, rule: Any) -> str | None:
    """The SQL expression giving one row of ``table`` (alias t) its owner, or None to copy."""
    if rule == "account":
        return (
            "(SELECT a.owner_user_id FROM accounts a"
            " WHERE a.tenant_id = t.tenant_id AND a.id = t.account_id)"
        )
    if rule == "run":
        return (
            "COALESCE((SELECT a.owner_user_id FROM account_runs r JOIN accounts a"
            " ON a.tenant_id = r.tenant_id AND a.id = r.account_id"
            " WHERE r.tenant_id = t.tenant_id AND r.id = t.run_id),"
            " (SELECT a.owner_user_id FROM runs r JOIN accounts a"
            " ON a.tenant_id = r.tenant_id AND a.id = r.account_id"
            " WHERE r.tenant_id = t.tenant_id AND r.id = t.run_id))"
        )
    if isinstance(rule, dict) and "parent" in rule:
        parent, column = str(rule["parent"]).split(".")
        return (
            f"(SELECT p.owner_user_id FROM {parent} p"
            f" WHERE p.tenant_id = t.tenant_id AND p.id = t.{column})"
        )
    if isinstance(rule, dict) and "column" in rule:
        return None if rule["column"] == "owner_user_id" else f"t.{rule['column']}"
    raise ValueError(f"{table}: unknown ownership rule {rule!r}")


def _trigger_args(rule: Any) -> str | None:
    """``fill_owner`` arguments for ``rule``, or None when nothing can be derived."""
    if rule in ("account", "run"):
        return f"'{rule}'"
    if isinstance(rule, dict) and "parent" in rule:
        parent, column = str(rule["parent"]).split(".")
        return f"'parent', '{parent}', '{column}'"
    if isinstance(rule, dict) and rule.get("column") not in (None, "owner_user_id"):
        return f"'column', '{rule['column']}'"
    return None


def _rule_name(rule: Any) -> str:
    if isinstance(rule, dict):
        key, value = next(iter(rule.items()))
        return f"{key}:{value}"
    return str(rule)


def render(cfg: dict[str, Any]) -> tuple[str, str]:
    """The up and down SQL."""
    owned: dict[str, Any] = cfg["owned"]
    up = [HEADER]
    up.append(
        """CREATE FUNCTION app_user() RETURNS text
   LANGUAGE sql STABLE SET search_path = public, pg_temp AS $$
   SELECT nullif(current_setting('app.user_id', true), '')
$$;
CREATE FUNCTION app_scope() RETURNS text
   LANGUAGE sql STABLE SET search_path = public, pg_temp AS $$
   SELECT coalesce(nullif(current_setting('app.scope', true), ''), 'user')
$$;
-- The one place that decides whether the caller may see a row of an owned table. A future
-- "share with my team" setting changes this function (and the generator's policy text) only.
CREATE FUNCTION owner_visible(p_owner text) RETURNS boolean
   LANGUAGE sql STABLE SET search_path = public, pg_temp AS $$
   SELECT app_scope() = 'system' OR p_owner = app_user()
$$;
GRANT EXECUTE ON FUNCTION app_user(), app_scope(), owner_visible(text) TO app_rw;

-- How existing rows got their owner: one row per table and client (migration record only).
CREATE TABLE ownership_backfill (
   table_name     text NOT NULL,
   tenant_id      uuid NOT NULL,
   rule           text NOT NULL,
   derived_rows   bigint NOT NULL,
   fallback_rows  bigint NOT NULL,
   at             timestamptz NOT NULL DEFAULT now(),
   CONSTRAINT pk_ownership_backfill PRIMARY KEY (table_name, tenant_id)
);
ALTER TABLE ownership_backfill ENABLE ROW LEVEL SECURITY;
ALTER TABLE ownership_backfill FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON ownership_backfill TO app_rw
   USING (tenant_id = (SELECT app_tenant())) WITH CHECK (false);
GRANT SELECT ON ownership_backfill TO app_rw;

-- Give an inserted row its owner by the same rule as the backfill, whoever writes it: a row
-- owned through its account, run or parent always takes that parent's owner (so a user writing
-- into another user's account is refused by the policy, and a system job writing for a user
-- needs no owner of its own); a row whose owner is one of its own columns (user_id, added_by,
-- uploaded_by) copies that column when it is set. When no owner can be found the acting user's
-- default stays, and with none NOT NULL refuses the row.
CREATE FUNCTION fill_owner() RETURNS trigger
   LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
DECLARE
   found text;
BEGIN
   IF TG_ARGV[0] = 'account' THEN
      SELECT a.owner_user_id INTO found FROM accounts a
       WHERE a.tenant_id = NEW.tenant_id AND a.id = NEW.account_id;
   ELSIF TG_ARGV[0] = 'run' THEN
      SELECT a.owner_user_id INTO found FROM account_runs r
        JOIN accounts a ON a.tenant_id = r.tenant_id AND a.id = r.account_id
       WHERE r.tenant_id = NEW.tenant_id AND r.id = NEW.run_id;
      IF found IS NULL THEN
         SELECT a.owner_user_id INTO found FROM runs r
           JOIN accounts a ON a.tenant_id = r.tenant_id AND a.id = r.account_id
          WHERE r.tenant_id = NEW.tenant_id AND r.id = NEW.run_id;
      END IF;
   ELSIF TG_ARGV[0] = 'parent' THEN
      EXECUTE format('SELECT p.owner_user_id FROM %I p WHERE p.tenant_id = $1 AND p.id = ($2).%I',
                     TG_ARGV[1], TG_ARGV[2])
         INTO found USING NEW.tenant_id, NEW;
   ELSIF TG_ARGV[0] = 'column' THEN
      found := to_jsonb(NEW) ->> TG_ARGV[1];
   END IF;
   NEW.owner_user_id := coalesce(found, NEW.owner_user_id);
   RETURN NEW;
END
$$;
GRANT EXECUTE ON FUNCTION fill_owner() TO app_rw;

-- The client's first user (by when the user row was made); system:unowned when it has none.
CREATE FUNCTION pg_temp.first_user(p_tenant uuid) RETURNS text LANGUAGE sql STABLE AS $$
   SELECT coalesce((SELECT u.subject FROM users u WHERE u.tenant_id = p_tenant
                     ORDER BY u.created_at, u.subject LIMIT 1), 'system:unowned')
$$;
"""
    )
    down = [
        "-- Reverse migration 0063 (GENERATED by scripts/gen_ownership_migration.py). Restoring the"
        " one-account-per-domain\n-- key fails if two users of one client added the same company.",
        "ALTER TABLE accounts DROP CONSTRAINT IF EXISTS uq_accounts_tenant_owner_domain;",
    ]
    for table, rule in owned.items():
        expr = _owner_expr(table, rule)
        has_column = isinstance(rule, dict) and rule.get("column") == "owner_user_id"
        policy = POLICY_NAMES.get(table, "tenant_isolation")
        up.append(f"\n-- {table} ({_rule_name(rule)})")
        if not has_column:
            up.append(f"ALTER TABLE {table} ADD COLUMN owner_user_id text;")
        # append-only and audit triggers refuse UPDATE; the backfill is the one sanctioned write
        up.append(f"ALTER TABLE {table} DISABLE TRIGGER USER;")
        if expr is not None:
            up.append(f"UPDATE {table} t SET owner_user_id = {expr} WHERE t.owner_user_id IS NULL;")
        up.append(
            "INSERT INTO ownership_backfill (table_name, tenant_id, rule, derived_rows,"
            " fallback_rows)\n"
            f"   SELECT '{table}', t.tenant_id, '{_rule_name(rule)}',"
            " count(*) FILTER (WHERE t.owner_user_id IS NOT NULL),"
            f" count(*) FILTER (WHERE t.owner_user_id IS NULL) FROM {table} t GROUP BY t.tenant_id;"
        )
        up.append(
            f"UPDATE {table} t SET owner_user_id = pg_temp.first_user(t.tenant_id)"
            " WHERE t.owner_user_id IS NULL;"
        )
        up.append(f"ALTER TABLE {table} ENABLE TRIGGER USER;")
        up.append(
            f"ALTER TABLE {table} ALTER COLUMN owner_user_id SET DEFAULT app_user(),"
            " ALTER COLUMN owner_user_id SET NOT NULL;"
        )
        up.append(f"CREATE INDEX ix_{table}_tenant_owner ON {table} (tenant_id, owner_user_id);")
        args = _trigger_args(rule)
        if args is not None:
            column = rule.get("column") if isinstance(rule, dict) else None
            when = f"\n   WHEN (NEW.{column} IS NOT NULL)" if column else ""
            up.append(
                f"CREATE TRIGGER fill_owner BEFORE INSERT ON {table} FOR EACH ROW{when}"
                f" EXECUTE FUNCTION fill_owner({args});"
            )
        up.append(f"DROP POLICY {policy} ON {table};")
        up.append(
            f"CREATE POLICY tenant_owner_isolation ON {table} TO app_rw\n"
            f"   USING ({TENANT} AND {OWNER})\n"
            f"   WITH CHECK ({TENANT} AND {OWNER});"
        )
        down.append(f"\n-- {table}")
        down.append(f"DROP POLICY IF EXISTS tenant_owner_isolation ON {table};")
        down.append(
            f"CREATE POLICY {policy} ON {table} TO app_rw\n"
            f"   USING ({TENANT}) WITH CHECK ({TENANT});"
        )
        down.append(f"DROP INDEX IF EXISTS ix_{table}_tenant_owner;")
        if _trigger_args(rule) is not None:
            down.append(f"DROP TRIGGER IF EXISTS fill_owner ON {table};")
        if has_column:
            down.append(
                f"ALTER TABLE {table} ALTER COLUMN owner_user_id DROP DEFAULT,"
                " ALTER COLUMN owner_user_id DROP NOT NULL;"
            )
        else:
            down.append(f"ALTER TABLE {table} DROP COLUMN IF EXISTS owner_user_id;")
    for key in cfg.get("unique_per_owner", []):
        table, cols = key["table"], ", ".join(key["columns"])
        new_name = f"uq_{table}_tenant_owner_{'_'.join(key['columns'])}"
        where = f" WHERE ({key['where']})" if key.get("where") else ""
        up.append(f"\n-- {table}: unique per user ({cols})")
        down.append(f"\n-- {table}: unique per client again ({cols})")
        if "constraint" in key:
            up.append(f"ALTER TABLE {table} DROP CONSTRAINT {key['constraint']};")
            up.append(
                f"ALTER TABLE {table} ADD CONSTRAINT {new_name}"
                f" UNIQUE (tenant_id, owner_user_id, {cols});"
            )
            down.append(f"ALTER TABLE {table} DROP CONSTRAINT IF EXISTS {new_name};")
            down.append(
                f"ALTER TABLE {table} ADD CONSTRAINT {key['constraint']}"
                f" UNIQUE (tenant_id, {cols});"
            )
        else:
            up.append(f"DROP INDEX {key['index']};")
            up.append(
                f"CREATE UNIQUE INDEX {new_name} ON {table}"
                f" (tenant_id, owner_user_id, {cols}){where};"
            )
            down.append(f"DROP INDEX IF EXISTS {new_name};")
            down.append(
                f"CREATE UNIQUE INDEX {key['index']} ON {table} (tenant_id, {cols}){where};"
            )
    up.append(
        "\n-- Accounts: one company per user, so two users of one client can each research it.\n"
        "ALTER TABLE accounts DROP CONSTRAINT uq_accounts_tenant_id_domain;\n"
        "ALTER TABLE accounts ADD CONSTRAINT uq_accounts_tenant_owner_domain\n"
        "   UNIQUE (tenant_id, owner_user_id, domain);"
    )
    down.append(
        "\nALTER TABLE accounts ADD CONSTRAINT uq_accounts_tenant_id_domain\n"
        "   UNIQUE (tenant_id, domain);\n"
        "DROP TABLE IF EXISTS ownership_backfill;\n"
        "DROP FUNCTION IF EXISTS fill_owner();\n"
        "DROP FUNCTION IF EXISTS owner_visible(text);\n"
        "DROP FUNCTION IF EXISTS app_scope();\n"
        "DROP FUNCTION IF EXISTS app_user();"
    )
    return "\n".join(up) + "\n", "\n".join(down) + "\n"


def main(argv: list[str]) -> int:
    cfg = yaml.safe_load(CONFIG.read_text())
    up, down = render(cfg)
    if "--check" in argv:
        stale = [
            p.name
            for p, body in ((UP, up), (DOWN, down))
            if not p.exists() or p.read_text() != body
        ]
        if stale:
            print(f"ownership migration is stale: run scripts/gen_ownership_migration.py ({stale})")
            return 1
        print("ownership migration OK")
        return 0
    UP.write_text(up)
    DOWN.write_text(down)
    print(f"wrote {UP.relative_to(ROOT)} and {DOWN.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
