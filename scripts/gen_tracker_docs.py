"""Generate docs/tracker/transitions.md from config/tracker_v1.yaml (never edited by hand).

Usage: ``python scripts/gen_tracker_docs.py`` writes the file; ``--check`` exits 1 when stale.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs/tracker/transitions.md"
STATES = ("unset", "not_done", "blocked", "partial", "none", "done")
TARGETS = ("done", "partial", "not_done", "blocked", "none")


def render() -> str:
    """The markdown the config implies."""
    data = yaml.safe_load((ROOT / "config/tracker_v1.yaml").read_text())
    table = data["transitions"]
    lines = [
        "# Tracker transition table (proposal D-13)",
        "",
        "Generated by `scripts/gen_tracker_docs.py` from `config/tracker_v1.yaml`"
        f" (version {data['version']}, status {data['status']}); do not edit by hand.",
        "Enforced by `src/account_intelligence/tracker/machine.py`; every cell is tested against a"
        " hand-written oracle in `tests/tracker/test_tables.py`.",
        "",
        "Actor rules apply before any cell (T7): a stage must own the row, the verifier only its"
        " configured rows, the judge and the gate only the downgrade cells, the finalizer only"
        " the unset to not_done sweep.",
        "",
        "| From \\ To | " + " | ".join(TARGETS) + " |",
        "| --- |" + " --- |" * len(TARGETS),
    ]
    for state in STATES:
        cells = [", ".join(table.get(state, {}).get(t, [])) or "no" for t in TARGETS]
        lines.append(f"| {state} | " + " | ".join(cells) + " |")
    lines += ["", "## Reason codes (client text)", "", "| Code | Client text |", "| --- | --- |"]
    lines += [f"| `{code}` | {text} |" for code, text in sorted(data["reason_codes"].items())]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    """Write or check the document."""
    text = render()
    if "--check" in argv:
        if OUT.read_text() != text:
            print("stale: run python scripts/gen_tracker_docs.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
