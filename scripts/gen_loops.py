"""Generate docs/architecture/loops.md from ``# LOOP(<name>): cap=...; exit=...`` comments (W8).

Every ``while`` statement in ``src`` must carry a LOOP comment on the line(s) just above it, and
so must every bounded retry, re-ask, pass or poll loop; the inventory is the comments themselves,
so it cannot drift from the code. ``--check`` exits 1 when the file is stale or a ``while`` loop
has no annotation.
"""

from __future__ import annotations

import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs/architecture/loops.md"
LOOP = re.compile(r"#\s*LOOP\(([^)]+)\):\s*cap=(.*?);\s*exit=(.*)$")


def scan() -> tuple[list[tuple[str, int, str, str, str]], list[str]]:
    """Annotated loops and unannotated ``while`` statements."""
    rows: list[tuple[str, int, str, str, str]] = []
    missing: list[str] = []
    for path in sorted((ROOT / "src").rglob("*.py")):
        rel = str(path.relative_to(ROOT))
        source = path.read_text()
        lines = source.split("\n")
        for i, line in enumerate(lines):
            if "# LOOP(" not in line:
                continue
            block, cont = [line.strip().lstrip("#").strip()], i + 1
            while cont < len(lines) and lines[cont].strip().startswith("#"):
                block.append(lines[cont].strip().lstrip("#").strip())
                cont += 1
            m = LOOP.search("# " + " ".join(block))
            if m is None:
                missing.append(f"{rel}:{i + 1} (malformed LOOP comment)")
                continue
            rows.append((m.group(1).strip(), cont + 1, rel, m.group(2).strip(), m.group(3).strip()))
        for node in ast.walk(ast.parse(source)):
            if isinstance(node, ast.While):
                window = lines[max(0, node.lineno - 4) : node.lineno - 1]
                if not any("# LOOP(" in w for w in window):
                    missing.append(f"{rel}:{node.lineno}")
    return rows, missing


def render() -> str:
    """The markdown inventory."""
    rows, _ = scan()
    out = [
        "# Loop inventory (W8)",
        "",
        "Generated by `scripts/gen_loops.py` from `# LOOP(...)` comments in `src`; do not edit by",
        "hand. Every loop has a hard cap and records why it stopped; no `while` loop is",
        "unannotated (the generator's check fails otherwise).",
        "",
        "| Loop | Where | Cap | Exit reasons |",
        "| --- | --- | --- | --- |",
    ]
    for name, line, rel, cap, exits in sorted(rows):
        out.append(f"| {name} | `{rel}:{line}` | {cap} | {exits} |")
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    """Write or check the inventory."""
    _, missing = scan()
    if missing:
        print(f"while loops without a LOOP annotation: {missing}", file=sys.stderr)
        return 1
    text = render()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("stale: run python scripts/gen_loops.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
