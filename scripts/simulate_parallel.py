"""Write ``docs/parallel/simulation-report.md`` from a fixed synthetic scenario (D-44).

A SIMULATION with stub providers and scripted latencies: it exercises the real scheduler, the real
dependency plan and the real governor rule on a virtual clock. It measures nothing about real
providers and never claims the 4 hour target is met. ``--check`` exits 1 when the file is stale.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from parallel.config import load_parallel_config  # noqa: E402
from parallel.simulate import Scenario, simulate  # noqa: E402

OUT = ROOT / "docs/parallel/simulation-report.md"
ROUTES = ["people_by_title", "profile_enrichment", "scrape", "structured_signals", "web_search"]
LATENCY_S = 60.0  # scripted, synthetic: every unit takes one virtual minute
STORED = {
    "senior_people": [f"person-{i:02d}" for i in range(12)],
    "top_people": [f"person-{i:02d}" for i in range(10)],
    "priority_a_people": [f"person-{i:02d}" for i in range(4)],
}


def render() -> str:
    """The report for 1 run unconstrained, 1 run at limits 4 and 1, and 50 runs at limit 3."""
    cfg = load_parallel_config()
    latency = {t: LATENCY_S for t in cfg.unit_types}
    parts = [
        "<!-- generated by scripts/simulate_parallel.py; do not edit -->",
        "",
        f"Scenario: synthetic; every unit takes {LATENCY_S:.0f} virtual seconds; 12 senior people,",
        "top ten people, 4 priority A people; all six lanes; stub providers whose true",
        "concurrency equals the governor ceiling.",
        "",
    ]
    cases = [
        ("1 run, unconstrained", 1, 10_000, 10_000),
        ("1 run, provider limit 4", 1, 4, 8),
        ("1 run, provider limit 1", 1, 1, 8),
        ("50 runs, provider limit 3", 50, 3, 8),
    ]
    for title, runs, limit, in_flight in cases:
        report = simulate(
            cfg,
            Scenario(
                runs=runs,
                latency_s=latency,
                stored=STORED,
                provider_limits={r: limit for r in ROUTES},
                governor_ceilings={r: limit for r in ROUTES},
                max_in_flight=in_flight,
            ),
        )
        parts += [f"## {title}", "", report.markdown().replace("# Parallel", "### Parallel"), ""]
    return "\n".join(parts)


def main() -> int:
    """Write the report, or check it with ``--check``."""
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print("stale: run python scripts/simulate_parallel.py")
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
