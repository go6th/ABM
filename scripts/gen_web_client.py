"""Web client generator (D-91 step 0, F3 and F5): one source for the client's types and labels.

Reads the committed OpenAPI snapshot (``docs/api/openapi.json``) and the server's own label
sources, and writes:

* ``web/lib/gen/api.gen.ts``: a zod schema per component (runtime validation of every reply)
  and the operation table (method, path, plane, success schema). Enumerations in replies are
  generated as plain strings with their known values listed separately, so a value the client
  has never seen renders as ``Unknown (code)`` instead of failing the whole reply (F8).
* ``web/lib/gen/labels.gen.ts``: the label maps the screens use (run statuses, coverage
  statuses, product grades, live spend states, feedback reasons, alert rules, lanes) taken from
  the server modules and configuration that already define them, plus the client-output
  denylist patterns (U3).

``--check`` writes nothing and exits 1 when either file would change (the CI drift gate).
Usage: ``python scripts/gen_web_client.py [--check]``
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent
SNAPSHOT = ROOT / "docs" / "api" / "openapi.json"
OUT = ROOT / "web" / "lib" / "gen"
HEADER = "// GENERATED by scripts/gen_web_client.py from {src}. Do not edit; run the script.\n"


def _ident(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", name)


def _refs(node: Any) -> set[str]:
    found: set[str] = set()
    if isinstance(node, dict):
        ref = node.get("$ref")
        if isinstance(ref, str):
            found.add(ref.rsplit("/", 1)[-1])
        for value in node.values():
            found |= _refs(value)
    elif isinstance(node, list):
        for value in node:
            found |= _refs(value)
    return found


def _order(schemas: dict[str, Any]) -> list[str]:
    """Components in dependency order (a schema after every schema it references)."""
    done: list[str] = []
    seen: set[str] = set()

    def visit(name: str, stack: tuple[str, ...]) -> None:
        if name in seen:
            return
        if name in stack:
            raise ValueError(f"recursive schema {name}: not supported by the generator")
        for dep in sorted(_refs(schemas[name])):
            visit(dep, (*stack, name))
        seen.add(name)
        done.append(name)

    for name in sorted(schemas):
        visit(name, ())
    return done


def zod(node: dict[str, Any]) -> str:
    """One JSON schema node as a zod expression."""
    if "$ref" in node:
        return _ident(node["$ref"].rsplit("/", 1)[-1])
    if "anyOf" in node:
        options = node["anyOf"]
        nullable = any(o.get("type") == "null" for o in options)
        rest = [o for o in options if o.get("type") != "null"]
        inner = zod(rest[0]) if len(rest) == 1 else f"z.union([{', '.join(zod(o) for o in rest)}])"
        if not rest:
            inner = "z.null()"
        return f"{inner}.nullable()" if nullable and rest else inner
    if "const" in node:
        return f"z.literal({json.dumps(node['const'])})"
    kind = node.get("type")
    if kind == "string" or "enum" in node:
        return "z.string()"
    if kind == "integer":
        return "z.number().int()"
    if kind == "number":
        return "z.number()"
    if kind == "boolean":
        return "z.boolean()"
    if kind == "null":
        return "z.null()"
    if kind == "array":
        return f"z.array({zod(node.get('items', {}))})"
    if kind == "object" or "properties" in node:
        props = node.get("properties")
        if props:
            required = set(node.get("required", []))
            fields = []
            for key in sorted(props):
                expr = zod(props[key])
                if key not in required:
                    expr += ".optional()"
                fields.append(f"  {json.dumps(key)}: {expr},")
            expression = "z.object({\n" + "\n".join(fields) + "\n})"
            if node.get("additionalProperties") is False:
                expression += ".strict()"
            return expression
        extra = node.get("additionalProperties")
        if isinstance(extra, dict) and extra:
            return f"z.record(z.string(), {zod(extra)})"
        return "z.record(z.string(), z.unknown())"
    return "z.unknown()"


def _success(op: dict[str, Any]) -> tuple[str, dict[str, Any] | None]:
    for code in ("200", "201", "202"):
        found = op.get("responses", {}).get(code)
        if found is not None:
            content = found.get("content", {})
            schema = content.get("application/json", {}).get("schema")
            return code, schema if schema else None
    return "204", None


def _request(op: dict[str, Any]) -> tuple[dict[str, Any] | None, bool]:
    """The JSON request schema and whether the request body is required."""
    request = op.get("requestBody") or {}
    content = request.get("content", {})
    media = content.get("application/json") or next(iter(content.values()), {})
    schema = media.get("schema") if isinstance(media, dict) else None
    return schema, bool(request.get("required", False))


def _plane(path: str) -> str:
    return "operator" if path.startswith("/operator/") else "tenant"


def api_module(doc: dict[str, Any]) -> str:
    """The zod schemas and the operation table."""
    schemas = doc["components"]["schemas"]
    lines = [HEADER.format(src="docs/api/openapi.json"), 'import { z } from "zod";', ""]
    enums: dict[str, list[str]] = {}
    for name in _order(schemas):
        node = schemas[name]
        ident = _ident(name)
        lines.append(f"export const {ident} = {zod(node)};")
        lines.append(f"export type {ident} = z.infer<typeof {ident}>;")
        for key, prop in sorted((node.get("properties") or {}).items()):
            values = prop.get("enum") or next(
                (o.get("enum") for o in prop.get("anyOf", []) if o.get("enum")), None
            )
            if values:
                enums[f"{ident}.{key}"] = [str(v) for v in values]
        lines.append("")
    lines.append("/** Known values of enumerated fields (labels map them; others are Unknown). */")
    lines.append(
        f"export const KNOWN_VALUES = {json.dumps(enums, indent=2, sort_keys=True)} as const;"
    )
    lines.append("")
    lines.append("export interface Operation {")
    lines.append('  method: "GET" | "POST" | "PUT" | "PATCH" | "DELETE";')
    lines.append("  path: string;")
    lines.append('  plane: "tenant" | "operator";')
    lines.append("  status: number;")
    lines.append("  request: z.ZodType | null;")
    lines.append("  requestRequired: boolean;")
    lines.append("  response: z.ZodType | null;")
    lines.append("}")
    lines.append("")
    lines.append("export const operations = {")
    for path in sorted(doc["paths"]):
        for method in sorted(doc["paths"][path]):
            op = doc["paths"][path][method]
            code, schema = _success(op)
            request_schema, request_required = _request(op)
            request = zod(request_schema) if request_schema is not None else "null"
            response = zod(schema) if schema is not None else "null"
            key = f"{method.upper()} {path}"
            lines.append(
                f"  {json.dumps(key)}: {{ method: {json.dumps(method.upper())}, path:"
                f" {json.dumps(path)}, plane: {json.dumps(_plane(path))}, status: {code},"
                f" request: {request}, requestRequired: {str(request_required).lower()},"
                f" response: {response} }},"
            )
    lines.append("} as const satisfies Record<string, Operation>;")
    lines.append("")
    lines.append("export type OperationKey = keyof typeof operations;")
    lines.append(
        "export type TenantOperation = { [K in OperationKey]: (typeof operations)[K] extends"
        ' { plane: "tenant" } ? K : never }[OperationKey];'
    )
    lines.append(
        "export type OperatorOperation = { [K in OperationKey]: (typeof operations)[K] extends"
        ' { plane: "operator" } ? K : never }[OperationKey];'
    )
    lines.append(
        "export type ReplyOf<K extends OperationKey> = (typeof operations)[K]['response'] extends"
        " z.ZodType ? z.infer<NonNullable<(typeof operations)[K]['response']>> : undefined;"
    )
    return "\n".join(lines) + "\n"


def _load_labels() -> dict[str, Any]:
    import os

    sys.path[:0] = [str(ROOT / "scripts"), str(ROOT / "src"), str(ROOT)]
    from export_openapi import INERT

    for key, value in INERT.items():
        os.environ.setdefault(key, value)
    from account_intelligence.tracker.render import STATUS_TEXT
    from spend.live import TENANT_STATUS  # noqa: I001 - after the path is set
    from views.progress import STATUS_LABELS

    grading = yaml.safe_load((ROOT / "config" / "grading.yaml").read_text())
    pilot = yaml.safe_load((ROOT / "config" / "pilot.yaml").read_text())
    lanes = yaml.safe_load((ROOT / "config" / "lanes.yaml").read_text())["lanes"]
    sourced = yaml.safe_load(
        (ROOT / ".claude/skills/account-intelligence-platform/assets/alert_rules.yaml").read_text()
    )["rules"]
    extra = yaml.safe_load((ROOT / "config" / "alerts_extra.yaml").read_text())
    rules = {r["id"]: {"tier": r["tier"], "trigger": r["trigger"]} for r in sourced}
    for rid, rule in (extra.get("rules") or {}).items():
        rules.setdefault(rid, {"tier": rule.get("tier", "digest"), "trigger": rid})
    deny = [
        line.strip()
        for line in (ROOT / "config" / "client_output_denylist.txt").read_text().splitlines()
        if line.strip() and not line.lstrip().startswith("#")
    ]
    product = {k: str(v.get("meaning", "")) for k, v in grading["product_grades"].items()}
    return {
        "RUN_STATUS": dict(STATUS_LABELS),
        "COVERAGE_STATUS": {k: v for k, v in STATUS_TEXT.items()},
        "PRODUCT_GRADES": product,
        "LIVE_SPEND_STATUS": {m.name: v for m, v in TENANT_STATUS.items()},
        "FEEDBACK_REASONS": pilot["feedback_reasons"],
        "ALERT_RULES": rules,
        "LANES": {str(lane["id"]): str(lane["label"]) for lane in lanes},
        "DENYLIST_PATTERNS": deny,
    }


def labels_module() -> str:
    """The label maps and the denylist patterns."""
    data = _load_labels()
    lines = [
        HEADER.format(src="server label sources and config/*.yaml"),
        "// Run statuses: views/progress.py STATUS_LABELS.",
        "// Coverage: tracker/render.py STATUS_TEXT. Grades: config/grading.yaml.",
        "// Spend: spend/live.py. Reasons: config/pilot.yaml. Lanes: config/lanes.yaml.",
        "// Alert rules: assets/alert_rules.yaml and config/alerts_extra.yaml.",
        "// Denylist: config/client_output_denylist.txt (one case-insensitive regex per entry).",
        "",
    ]
    for name, value in data.items():
        lines.append(
            f"export const {name} = {json.dumps(value, indent=2, sort_keys=True)} as const;"
        )
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    """Write the generated modules, or compare them with ``--check``."""
    doc = json.loads(SNAPSHOT.read_text())
    outputs = {OUT / "api.gen.ts": api_module(doc), OUT / "labels.gen.ts": labels_module()}
    if "--check" in argv:
        stale = [p for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        if stale:
            names = ", ".join(str(p.relative_to(ROOT)) for p in stale)
            print(f"generated client drift: {names}; run python scripts/gen_web_client.py")
            return 1
        print("generated client OK")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for path, text in outputs.items():
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
