import { start, summarize, BASE, OUT } from "./lib.mjs";
const { browser, ctx, page, log } = await start();
const ok = (name, pass, ev = "") => console.log((pass ? "PASS " : "FAIL ") + name + (ev ? " :: " + ev : ""));
await page.goto(BASE + "/research/new", { waitUntil: "networkidle" });
await page.getByPlaceholder("Company name").first().fill("Nimbus Labs");
await page.getByPlaceholder("company.com").fill("nimbuslabs.example");
await page.getByRole("button", { name: "Start research" }).click();
await page.getByRole("button", { name: "Proceed" }).click();
await page.waitForTimeout(3000);
console.log("after Proceed url:", page.url());
await page.goto(BASE + "/research", { waitUntil: "networkidle" });
await page.waitForTimeout(6000);
let txt = (await page.innerText("main")).replace(/\n+/g, " | ");
console.log(txt.slice(0, 500));
ok("running research shows Stop", (await page.getByRole("button", { name: "Stop", exact: true }).count()) > 0);
await page.screenshot({ path: `${OUT}/shot-research-running.png`, fullPage: true });
await page.getByRole("button", { name: "Stop", exact: true }).first().click();
await page.waitForTimeout(1200);
console.log("after Stop click:", (await page.innerText("main")).replace(/\n+/g, " | ").slice(0, 400));
console.log(JSON.stringify(await page.$$eval("main button", (b) => b.map((x) => x.textContent.trim()).filter((t) => /Stop|Cancel|Keep|Confirm|Yes/.test(t)))));
const conf = page.getByRole("button", { name: /^(Stop research|Yes, stop|Stop it|Confirm)/ });
if (await conf.count()) await conf.first().click();
await page.waitForTimeout(4000);
txt = (await page.innerText("main")).replace(/\n+/g, " | ");
console.log("final:", txt.slice(0, 600));
await page.screenshot({ path: `${OUT}/shot-research-stopped.png`, fullPage: true });
console.log(JSON.stringify(summarize(log, "console-site10.json"), null, 1).split("\n").filter((l) => !/inline style/.test(l)).join("\n"));
await browser.close();
